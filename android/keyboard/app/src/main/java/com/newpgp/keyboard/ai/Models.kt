package com.newpgp.keyboard.ai

/**
 * Description of one locally runnable rewrite model.
 *
 * Model binaries are produced by `tools/convert_grammar_model.py` in CI and are never
 * committed to this repository. See `assets/models/README.md` for placement and
 * licensing details.
 */
data class ModelInfo(
    /** Stable identifier used by [ToneEngine.setModel]. */
    val id: String,
    /** Human-readable name shown in settings, e.g. "Grammar Small (offline)". */
    val displayName: String,
    /** File name inside `assets/models/` (encoder); decoder is `<name without .tflite>_decoder.tflite`. */
    val fileName: String,
    /** Approximate combined on-disk size in bytes (used only for UI hints). */
    val approxSizeBytes: Long,
    /** Short plain-language description. */
    val description: String,
    /** SPDX-style license note for the weights and the training data. */
    val license: String,
    /** Whether this model is expected to be bundled by CI. */
    val bundled: Boolean = true
)

/** Default model, generated by the conversion script from `pszemraj/grammar-synthesis-small`. */
val GRAMMAR_SMALL_MODEL: ModelInfo = ModelInfo(
    id = "grammar-small",
    displayName = "Grammar Small (offline)",
    fileName = "grammar_small_q8.tflite",
    // ~77M parameters at 8 bits = ~77 MB (plus metadata). The 4-bit recipe is ~38 MB.
    approxSizeBytes = 80L * 1024L * 1024L,
    description = "Small English grammar-correcting model. Runs on this device; no network access.",
    // Weights: apache-2.0. Training data (JFLEG / grammar-synthesis dataset): cc-by-nc-sa-4.0.
    // The dataset license may restrict commercial use; see assets/models/README.md.
    license = "weights: Apache-2.0; training data: CC BY-NC-SA 4.0 (non-commercial caveat)",
    bundled = true
)

/**
 * Registry of selectable models. Users can add their own later via [register]; nothing
 * in this class reads the network or the filesystem.
 */
class ModelRegistry(initial: List<ModelInfo> = listOf(GRAMMAR_SMALL_MODEL)) {

    private val models = LinkedHashMap<String, ModelInfo>()

    /** Id selected on first use. */
    var defaultId: String = GRAMMAR_SMALL_MODEL.id

    init {
        for (model in initial) models[model.id] = model
    }

    /** Add or replace a model definition. Does not load any file. */
    fun register(model: ModelInfo) {
        models[model.id] = model
    }

    fun find(id: String): ModelInfo? = models[id]

    /** Snapshot, insertion ordered, for settings UI. */
    fun all(): List<ModelInfo> = models.values.toList()

    fun default(): ModelInfo = models[defaultId] ?: models.values.firstOrNull()
        ?: throw IllegalStateException("AIE_NO_MODELS")
}
